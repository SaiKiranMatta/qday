//! Rasterizes Inter (assets/fonts/InterVariable.ttf) into anti-aliased glyph
//! tables for qday-ui, so the device draws real typography without a font
//! engine. Run from the repo root after changing a style:
//!
//!     cargo run -p qday-fontgen
//!
//! Writes crates/qday-ui/src/fonts/generated.rs (Inter) and bricolage.rs
//! (Bricolage Grotesque, for the Neo-brutal theme), both checked in.

use std::fmt::Write as _;

use swash::scale::{Render, ScaleContext, Source};
use swash::shape::ShapeContext;
use swash::zeno::Format;
use swash::{FontRef, NormalizedCoord};

const FONT: &str = "assets/fonts/InterVariable.ttf";
const OUT: &str = "crates/qday-ui/src/fonts/generated.rs";
/// Printable ASCII.
const FIRST: u8 = 32;
const LAST: u8 = 126;

/// One text style: Rust name, pixel size, Inter weight (100-900).
const STYLES: &[(&str, f32, f32)] = &[
    ("CAPTION", 11.0, 560.0),
    ("BODY", 13.0, 420.0),
    ("BODY_STRONG", 13.0, 600.0),
    ("TITLE", 17.0, 620.0),
    ("HEADLINE", 24.0, 660.0),
    ("DISPLAY", 34.0, 560.0),
    ("HERO", 46.0, 300.0),
];

/// Bricolage Grotesque for the Neo-brutal theme: (name, size, weight).
const BRICOLAGE: &str = "assets/fonts/BricolageGrotesque.ttf";
const BRICOLAGE_OUT: &str = "crates/qday-ui/src/fonts/bricolage.rs";
const BRICOLAGE_STYLES: &[(&str, f32, f32)] = &[
    ("HERO", 42.0, 800.0),
    ("BIG", 30.0, 780.0),
    ("TITLE", 19.0, 720.0),
    ("BODY", 13.0, 520.0),
    ("CAP", 11.0, 680.0),
];

fn main() {
    let styles: Vec<(String, f32, f32)> = STYLES
        .iter()
        .map(|(n, s, w)| (n.to_string(), *s, *w))
        .collect();
    let mut out = String::new();
    writeln!(
        out,
        "// Generated by `cargo run -p qday-fontgen` from Inter (SIL OFL 1.1). Do not edit."
    )
    .unwrap();
    writeln!(
        out,
        "// Glyph alpha is 4 bits per pixel, two pixels per byte, high nibble first."
    )
    .unwrap();
    writeln!(out).unwrap();
    writeln!(out, "use super::{{Font, Glyph}};").unwrap();
    out.push_str(&generate(FONT, &styles));
    std::fs::create_dir_all("crates/qday-ui/src/fonts").unwrap();
    std::fs::write(OUT, out).unwrap();
    eprintln!("wrote {OUT}");

    let styles: Vec<(String, f32, f32)> = BRICOLAGE_STYLES
        .iter()
        .map(|(n, s, w)| (n.to_string(), *s, *w))
        .collect();
    let mut out = String::new();
    writeln!(out, "// Generated by `cargo run -p qday-fontgen` from Bricolage Grotesque (SIL OFL 1.1). Do not edit.").unwrap();
    writeln!(
        out,
        "// Glyph alpha is 4 bits per pixel, two pixels per byte, high nibble first."
    )
    .unwrap();
    writeln!(out).unwrap();
    writeln!(out, "use super::{{Font, Glyph}};").unwrap();
    out.push_str(&generate(BRICOLAGE, &styles));
    std::fs::write(BRICOLAGE_OUT, out).unwrap();
    eprintln!("wrote {BRICOLAGE_OUT}");
}

/// Rust source for `styles` of the font at `path`.
fn generate(path: &str, styles: &[(String, f32, f32)]) -> String {
    let data =
        std::fs::read(path).unwrap_or_else(|e| panic!("{path}: {e} (run from the repo root)"));
    let font = FontRef::from_index(&data, 0).expect("a font");
    let mut scale = ScaleContext::new();
    let mut shape = ShapeContext::new();
    let mut out = String::new();
    let mut total = 0;
    for (name, size, weight) in styles {
        let (name, size, weight) = (name.as_str(), *size, *weight);
        let coords: Vec<NormalizedCoord> = font
            .variations()
            .normalized_coords([("wght", weight)])
            .collect();
        let metrics = font.metrics(&coords).scale(size);
        let glyph_metrics = font.glyph_metrics(&coords).scale(size);
        let charmap = font.charmap();
        let mut scaler = scale
            .builder(font)
            .size(size)
            .normalized_coords(coords.iter())
            .hint(false)
            .build();

        let mut glyphs = String::new();
        let mut pixels: Vec<u8> = Vec::new();
        let mut advances = Vec::new();
        for ch in FIRST..=LAST {
            let id = charmap.map(ch as char);
            let advance = glyph_metrics.advance_width(id);
            advances.push(advance);
            let image = Render::new(&[Source::Outline])
                .format(Format::Alpha)
                .render(&mut scaler, id);
            let (left, top, w, h, alpha) = match image {
                Some(img) if img.placement.width > 0 && img.placement.height > 0 => (
                    img.placement.left,
                    img.placement.top,
                    img.placement.width,
                    img.placement.height,
                    img.data,
                ),
                _ => (0, 0, 0, 0, Vec::new()),
            };
            let offset = pixels.len();
            // Pack 4-bit alpha, two pixels per byte, each row starting on a byte.
            for row in alpha.chunks(w.max(1) as usize) {
                for pair in row.chunks(2) {
                    let hi = (pair[0] as u16 + 8).min(255) >> 4;
                    let lo = pair.get(1).map_or(0, |&a| (a as u16 + 8).min(255) >> 4);
                    pixels.push(((hi << 4) | lo) as u8);
                }
            }
            writeln!(
                glyphs,
                "    Glyph {{ left: {left}, top: {top}, w: {w}, h: {h}, advance: {}, offset: {offset} }}, // {:?}",
                (advance * 16.0).round() as u16,
                ch as char
            )
            .unwrap();
        }

        // Kerning: shape each pair and compare with the plain advances.
        let mut kerning = Vec::new();
        for a in FIRST..=LAST {
            for b in FIRST..=LAST {
                let text = format!("{}{}", a as char, b as char);
                let mut shaper = shape
                    .builder(font)
                    .size(size)
                    .normalized_coords(coords.iter())
                    .build();
                shaper.add_str(&text);
                let mut first_advance = None;
                shaper.shape_with(|cluster| {
                    if first_advance.is_none() {
                        first_advance = Some(cluster.glyphs.iter().map(|g| g.advance).sum::<f32>());
                    }
                });
                let plain = advances[(a - FIRST) as usize];
                let kern = ((first_advance.unwrap_or(plain) - plain) * 16.0).round() as i32;
                if kern.abs() >= 4 {
                    // At least a quarter pixel: worth storing.
                    kerning.push((a, b, kern.clamp(-127, 127) as i8));
                }
            }
        }

        let lower = name.to_lowercase();
        writeln!(out).unwrap();
        writeln!(out, "pub static {name}: Font = Font {{").unwrap();
        writeln!(out, "    size: {},", size as u8).unwrap();
        writeln!(out, "    ascent: {},", metrics.ascent.round() as i16).unwrap();
        writeln!(out, "    descent: {},", metrics.descent.round() as i16).unwrap();
        writeln!(out, "    first: {FIRST},").unwrap();
        writeln!(out, "    glyphs: &{}_GLYPHS,", name).unwrap();
        writeln!(out, "    pixels: &{}_PIXELS,", name).unwrap();
        writeln!(out, "    kerning: &{}_KERNING,", name).unwrap();
        writeln!(out, "}};").unwrap();
        writeln!(
            out,
            "static {name}_GLYPHS: [Glyph; {}] = [",
            (LAST - FIRST + 1)
        )
        .unwrap();
        out.push_str(&glyphs);
        writeln!(out, "];").unwrap();
        writeln!(
            out,
            "static {name}_PIXELS: [u8; {}] = {};",
            pixels.len(),
            byte_array(&pixels)
        )
        .unwrap();
        writeln!(
            out,
            "/// (left, right, adjustment in 1/16 px), sorted for binary search."
        )
        .unwrap();
        write!(
            out,
            "static {name}_KERNING: [(u8, u8, i8); {}] = [",
            kerning.len()
        )
        .unwrap();
        for (a, b, k) in &kerning {
            write!(out, "({a}, {b}, {k}),").unwrap();
        }
        writeln!(out, "];").unwrap();
        eprintln!(
            "{lower:>12}: {size} px wght {weight}, {} bytes of glyphs, {} kerning pairs",
            pixels.len(),
            kerning.len()
        );
        total += pixels.len() + kerning.len() * 3 + (LAST - FIRST + 1) as usize * 12;
    }

    eprintln!("{}: about {} KB", path, total / 1024);
    out
}

fn byte_array(bytes: &[u8]) -> String {
    let mut s = String::from("[");
    for (i, b) in bytes.iter().enumerate() {
        if i % 32 == 0 {
            s.push_str("\n    ");
        }
        write!(s, "{b},").unwrap();
    }
    s.push_str("\n]");
    s
}
