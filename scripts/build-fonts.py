#!/usr/bin/env python3
"""Turns Inter into 4-bit anti-aliased glyph atlases for qday-ui.

    scripts/build-fonts.py <path to InterVariable.ttf>

Writes crates/qday-ui/src/fonts/data.rs. Needs Pillow built with FreeType.
"""
import sys
from pathlib import Path

from PIL import ImageFont

OUT = Path(__file__).resolve().parent.parent / "crates/qday-ui/src/fonts/data.rs"
FIRST, LAST = 32, 126

# name, pixel size, weight
FACES = [
    ("SMALL", 11, 500),
    ("BODY", 13, 450),
    ("LABEL", 13, 600),
    ("TITLE", 17, 600),
    ("NUMBER", 20, 600),
    ("HERO", 30, 600),
]


def load(path, size, weight):
    font = ImageFont.truetype(path, size)
    values = []
    for axis in font.get_variation_axes():
        name = axis["name"]
        name = name.decode() if isinstance(name, bytes) else name
        if "eight" in name:
            values.append(weight)
        elif "ptical" in name:
            values.append(min(max(size, axis["minimum"]), axis["maximum"]))
        else:
            values.append(axis["default"])
    font.set_variation_by_axes(values)
    return font


def glyph(font, code):
    """Returns (width, height, left, top, advance, packed 4-bit rows)."""
    char = chr(code)
    advance = round(font.getlength(char))
    box = font.getbbox(char, anchor="ls")
    width, height = box[2] - box[0], box[3] - box[1]
    if width <= 0 or height <= 0:
        return 0, 0, 0, 0, advance, b""
    mask, offset = font.getmask2(char, mode="L", anchor="ls")
    mw, mh = mask.size
    rows = bytearray()
    for y in range(mh):
        line = [mask.getpixel((x, y)) >> 4 for x in range(mw)]
        if mw % 2:
            line.append(0)
        rows.extend((line[i] << 4) | line[i + 1] for i in range(0, len(line), 2))
    return mw, mh, offset[0], offset[1], advance, bytes(rows)


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    path = sys.argv[1]
    lines = [
        "//! Generated by scripts/build-fonts.py from Inter. Do not edit.",
        "",
        "use super::{Font, Glyph};",
        "",
    ]
    for name, size, weight in FACES:
        font = load(path, size, weight)
        ascent, descent = font.getmetrics()
        bitmap = bytearray()
        entries = []
        for code in range(FIRST, LAST + 1):
            width, height, left, top, advance, rows = glyph(font, code)
            entries.append(
                f"    Glyph {{ offset: {len(bitmap)}, width: {width}, height: {height}, "
                f"left: {left}, top: {top}, advance: {advance} }},"
            )
            bitmap.extend(rows)
        lines.append(f"static {name}_GLYPHS: [Glyph; {LAST - FIRST + 1}] = [")
        lines.extend(entries)
        lines.append("];")
        lines.append(f"static {name}_BITMAP: [u8; {len(bitmap)}] = [")
        for start in range(0, len(bitmap), 24):
            lines.append("    " + ", ".join(str(b) for b in bitmap[start : start + 24]) + ",")
        lines.append("];")
        lines.append(f"/// Inter at {size} px, weight {weight}.")
        lines.append(
            f"pub static {name}: Font = Font {{ ascent: {ascent}, descent: {descent}, "
            f"glyphs: &{name}_GLYPHS, bitmap: &{name}_BITMAP }};"
        )
        lines.append("")
        print(f"{name}: {size}px w{weight}, {len(bitmap)} bytes")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines))


if __name__ == "__main__":
    main()
